import React, { useState, useEffect } from "react";
import {
  View,
  Text,
  TextInput,
  TouchableOpacity,
  StyleSheet,
  ActivityIndicator,
  Alert,
  KeyboardAvoidingView,
  Platform,
} from "react-native";
import AsyncStorage from "@react-native-async-storage/async-storage";
import Ionicons from "@react-native-vector-icons/ionicons";
import { colors, radius, spacing } from "../utils/theme";
import { useSession } from "../store/session";

interface PartnerLockProps {
  children?: React.ReactNode;
  onUnlocked?: () => void;
}

const VALIDATE_CODE_URL = "https://lljsnoovvwexzebzbaal.supabase.co/functions/v1/validate-code";

export default function PartnerLock({ children, onUnlocked }: PartnerLockProps) {
  const [email, setEmail] = useState("");
  const [code, setCode] = useState("");
  const [loading, setLoading] = useState(false);
  const [checking, setChecking] = useState(true);
  const [isUnlocked, setIsUnlocked] = useState(false);

  const login = useSession((s) => s.login);

  useEffect(() => {
    checkSavedAccess();
  }, []);

  const checkSavedAccess = async () => {
    try {
      const savedEmail = await AsyncStorage.getItem("@goldcast_saved_email");
      const savedCode = await AsyncStorage.getItem("@goldcast_saved_code");

      if (savedEmail) setEmail(savedEmail);
      if (savedCode) setCode(savedCode);

      if (savedEmail && savedCode) {
        const res = await fetch(VALIDATE_CODE_URL, {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ email: savedEmail, code: savedCode }),
        });

        const data = await res.json();
        if (res.ok && data.success) {
          setIsUnlocked(true);
          onUnlocked?.();
          setChecking(false);
          return;
        }
      }
    } catch (e) {
      // Ignora erro de rede em segundo plano
    } finally {
      setChecking(false);
    }
  };

  const handleUnlock = async () => {
    const cleanEmail = email.trim().toLowerCase();
    const cleanCode = code.trim().toUpperCase();

    if (!cleanEmail || !cleanEmail.includes("@")) {
      Alert.alert("E-mail Obrigatório", "Por favor, informe um endereço de e-mail válido.");
      return;
    }

    if (!cleanCode) {
      Alert.alert("Código Obrigatório", "Por favor, digite o seu código de acesso.");
      return;
    }

    setLoading(true);

    try {
      const res = await fetch(VALIDATE_CODE_URL, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          email: cleanEmail,
          code: cleanCode,
        }),
      });

      const data = await res.json();

      if (!res.ok || !data.success) {
        Alert.alert("Acesso Negado", data.message || "Código ou e-mail inválido.");
        setLoading(false);
        return;
      }

      await AsyncStorage.setItem("@goldcast_saved_email", cleanEmail);
      await AsyncStorage.setItem("@goldcast_saved_code", cleanCode);

      if (data.serverUrl && data.username && data.password) {
        try {
          await login(data.serverUrl, data.username, data.password, true);
        } catch (loginErr) {
          // Mantém liberado caso o Xtream oscile
        }
      }

      setIsUnlocked(true);
      onUnlocked?.();
    } catch (err: any) {
      Alert.alert("Erro de Conexão", err.message || "Não foi possível validar o código.");
    } finally {
      setLoading(false);
    }
  };

  if (checking) {
    return (
      <View style={styles.centerContainer}>
        <ActivityIndicator size="large" color={colors.gold} />
      </View>
    );
  }

  if (isUnlocked && children) {
    return <>{children}</>;
  }

  return (
    <KeyboardAvoidingView
      behavior={Platform.OS === "ios" ? "padding" : "height"}
      style={styles.container}
    >
      <View style={styles.card}>
        <View style={styles.iconCircle}>
          <Ionicons name="shield-checkmark" size={38} color={colors.gold} />
        </View>

        <Text style={styles.tag}>ACESSO EXCLUSIVO POR PARCERIA</Text>

        <Text style={styles.label}>SEU E-MAIL</Text>
        <TextInput
          style={styles.input}
          placeholder="exemplo@gmail.com"
          placeholderTextColor="#666"
          value={email}
          onChangeText={setEmail}
          autoCapitalize="none"
          keyboardType="email-address"
          autoCorrect={false}
        />

        <Text style={styles.label}>CÓDIGO DE ACESSO</Text>
        <TextInput
          style={styles.input}
          placeholder="Ex: GOLD-VIP-365D"
          placeholderTextColor="#666"
          value={code}
          onChangeText={(t) => setCode(t.toUpperCase())}
          autoCapitalize="characters"
          autoCorrect={false}
        />

        <TouchableOpacity
          style={[styles.button, loading && styles.buttonDisabled]}
          onPress={handleUnlock}
          disabled={loading}
          activeOpacity={0.8}
        >
          {loading ? (
            <ActivityIndicator color="#000" />
          ) : (
            <Text style={styles.buttonText}>LIBERAR ACESSO</Text>
          )}
        </TouchableOpacity>

        <Text style={styles.footerText}>
          Ainda não tem um código? Entre em contato com seu revendedor ou suporte.
        </Text>
      </View>
    </KeyboardAvoidingView>
  );
}

